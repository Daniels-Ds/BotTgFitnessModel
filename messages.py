def profile_summary(data: dict) -> str:
    gender_label = "Мужчина" if data.get("gender") == "male" else "Женщина"
    act_map = {
        "act_low": "Малоподвижный",
        "act_mid": "Средняя активность",
        "act_high": "Регулярные тренировки",
    }
    from keyboards import MUSCLE_GROUPS

    muscles_lines: list[str] = []
    for key, short, _em in MUSCLE_GROUPS:
        pct = int(data.get("muscles", {}).get(key, 0) or 0)
        if pct:
            muscles_lines.append(f"  • {short}: +{pct}%")
    muscles_text = "\n".join(muscles_lines) if muscles_lines else "  • без акцентов (общий тонус)"
    return (
        f"<b>📋 Ваши параметры</b>\n"
        f"• {gender_label}, {data.get('age')} лет\n"
        f"• Рост: {data.get('height')} см, вес: {data.get('weight')} кг\n"
        f"• Активность: {act_map.get(data.get('activity', ''), '—')}\n\n"
        f"<b>🎯 Зоны:</b>\n{muscles_text}"
    )


