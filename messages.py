def progress_msg(elapsed: int) -> str:
    mins = elapsed // 60
    secs = elapsed % 60
    stages = [
        (0, "🔍 Определяем ракурсы фото…"),
        (30, "🎬 Первое видео — «сейчас»…"),
        (120, "✨ Правим кадры «после» (анфас и спина)…"),
        (240, "🎞 Второе видео — «после»…"),
    ]
    stage = stages[0][1]
    for t, s in stages:
        if elapsed >= t:
            stage = s
    return (
        f"⚙️ <b>Генерация двух видео</b>\n\n"
        f"{stage}\n\n"
        f"⏱ Прошло: <b>{mins}</b>м <b>{secs:02d}</b>с\n\n"
        f"{video_gen_wait_hint_html()}"
    )


