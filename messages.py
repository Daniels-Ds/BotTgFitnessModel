def progress_msg(elapsed: int) -> str:
    mins = elapsed // 60
    secs = elapsed % 60
    stages = [
        (0, "🔍 Запускаем пайплайн по вашим фото…"),
        (30, "🎬 Первое видео — «сейчас»…"),
        (120, "✨ Готовим кадр «после» и второе видео…"),
        (240, "🎞 Финальная сборка второго ролика…"),
    ]
    stage = stages[0][1]
    for t, s in stages:
        if elapsed >= t:
            stage = s
    return (
        f"⚙️ <b>Генерация двух видео</b>\n\n"
        f"{stage}\n\n"
        f"⏱ Прошло: <b>{mins}</b>м <b>{secs:02d}</b>с\n\n"
        f"{video_gen_wait_hint_html()}"
    )


